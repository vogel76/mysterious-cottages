/* Builds public/icons.svg — the SVG sprite used by markup that is not
   rendered by React (the legal pages, the admin editor). The symbols are
   the regular-weight glyphs of @phosphor-icons/core, the same icon family
   the React app uses through @phosphor-icons/react, so every surface of the
   site draws from one set.

   Which icons go in: src/ui/sprite-icons.json. Usage in HTML:
     <svg class="icon" aria-hidden="true" focusable="false">
       <use href="../icons.svg#arrow-left"/>
     </svg>
   Runs before `vite` in the dev and build scripts; the output is generated,
   never edited by hand, and ignored by git. */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const listFile = resolve(here, '../src/ui/sprite-icons.json')
const assetsDir = resolve(here, '../node_modules/@phosphor-icons/core/assets/regular')
const outFile = resolve(here, '../public/icons.svg')

const names = JSON.parse(readFileSync(listFile, 'utf8'))
if (!Array.isArray(names) || names.some((name) => typeof name !== 'string' || !/^[a-z0-9-]+$/.test(name))) {
  throw new Error(`${listFile}: expected an array of icon names (kebab-case)`)
}

const symbols = names.map((name) => {
  const svg = readFileSync(resolve(assetsDir, `${name}.svg`), 'utf8')
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1]
  const body = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1]?.trim()
  if (!viewBox || !body) throw new Error(`Unexpected SVG format: ${name}.svg`)
  return `  <symbol id="${name}" viewBox="${viewBox}">${body}</symbol>`
})

const sprite = [
  '<svg xmlns="http://www.w3.org/2000/svg">',
  '  <!-- Generated by scripts/build-icon-sprite.mjs from @phosphor-icons/core (regular). Do not edit. -->',
  ...symbols,
  '</svg>',
  '',
].join('\n')

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, sprite)
console.log(`wrote public/icons.svg (${names.length} icons)`)
